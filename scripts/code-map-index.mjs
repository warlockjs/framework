// Writes code-map/FILE_INDEX.md from code-map/graph.json: one line per source file with
// its top-level symbols (code) or title (docs pages), grouped by directory. Test files are
// counted, not listed. Deterministic: same graph in, same file out.
import { readFileSync, writeFileSync } from "node:fs";

const graphPath = process.argv[2] ?? "code-map/graph.json";
const outPath = process.argv[3] ?? "code-map/FILE_INDEX.md";
const MAX_SYMBOLS = 8;
const isTest = (path) => /\.(spec|test)\.[cm]?[jt]sx?$|(^|\/)__tests__\//.test(path);
const line = (location) => Number(String(location ?? "L0").slice(1)) || 0;
const clip = (text, max) => {
  const flat = String(text ?? "")
    .replace(/\s+/g, " ")
    .trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
};

const graph = JSON.parse(readFileSync(graphPath, "utf8"));
const files = new Map();
for (const node of graph.nodes) {
  const path = node.source_file;
  if (!path || path.includes("..") || path.startsWith("/")) continue;
  const entry = files.get(path) ?? { symbols: [], title: "" };
  files.set(path, entry);
  if (node.file_type === "document" && node.node_kind === "page") {
    entry.title = node.frontmatter?.title ?? node.frontmatter?.name ?? "";
    entry.description = node.frontmatter?.description ?? "";
  } else if (
    node.file_type === "code" &&
    !node.label.startsWith(".") &&
    node.label !== path.split("/").pop()
  ) {
    entry.symbols.push({
      label: node.label,
      at: line(node.source_location),
      cls: node._callable_class === true,
    });
  }
}

const groupOf = (path) => {
  const parts = path.split("/");
  if (parts[0] === "packages" || (parts[0] === "docs" && parts[1] === "src"))
    return parts.slice(0, parts[0] === "packages" ? 2 : 4).join("/");
  return parts.slice(0, Math.min(2, parts.length - 1)).join("/") || ".";
};

const groups = new Map();
const testCounts = new Map();
for (const path of [...files.keys()].sort()) {
  const group = groupOf(path);
  if (isTest(path)) {
    testCounts.set(group, (testCounts.get(group) ?? 0) + 1);
    continue;
  }
  const list = groups.get(group) ?? [];
  groups.set(group, list);
  const entry = files.get(path);
  const symbols = [...new Map(entry.symbols.map((s) => [s.label, s])).values()]
    .sort((a, b) => Number(b.cls) - Number(a.cls) || a.at - b.at)
    .slice(0, MAX_SYMBOLS)
    .map((s) => s.label.replace(/\(\)$/, ""));
  const summary = entry.title
    ? clip(entry.title, 70) + (entry.description ? ` - ${clip(entry.description, 90)}` : "")
    : symbols.join(", ");
  list.push(`- \`${path}\`${summary ? ` - ${summary}` : ""}`);
}

const out = [
  "# Code map: file index",
  "",
  "Generated by `pnpm code-map` (scripts/code-map-index.mjs) from `code-map/graph.json`. Do not edit.",
  "Each line is a source file followed by its main symbols (classes first) or, for docs pages, the title and description.",
  "Test files are counted per group, not listed. Search this file for a keyword to find the file that owns it.",
  "",
];
for (const group of [...groups.keys()].sort()) {
  const tests = testCounts.get(group);
  out.push(
    `## ${group}${tests ? ` (${tests} test files not listed)` : ""}`,
    "",
    ...groups.get(group),
    "",
  );
}
writeFileSync(outPath, `${out.join("\n")}\n`);
console.log(`code map: ${outPath} (${files.size} files)`);

/**
 * Add `import <line>` at the top of a source file unless the module is already
 * imported by name.
 *
 * @param source The file's current text.
 * @param importLine The full import statement, e.g. `import { x } from "pkg";`.
 * @returns The text with the import in front, or the same text when present.
 */
export function ensureImportLine(source: string, importLine: string): string {
  const specifier = /from\s+["']([^"']+)["']/.exec(importLine)?.[1];
  const name = /\{\s*([\w$]+)\s*\}/.exec(importLine)?.[1];

  if (specifier && name) {
    const existing = new RegExp(
      `import\\s*\\{[^}]*\\b${name}\\b[^}]*\\}\\s*from\\s*["']${specifier.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&")}["']`,
    );

    if (existing.test(source)) {
      return source;
    }
  }

  return `${importLine}\n${source}`;
}

/**
 * Add `.gitignore` lines that are missing, keeping the file as it is.
 *
 * @param source The `.gitignore` text.
 * @param lines The lines that must be present.
 * @returns The new text, or `null` when every line is already there.
 */
export function appendGitignoreLines(source: string, lines: readonly string[]): string | null {
  const present = new Set(source.split(/\r?\n/).map((line) => line.trim()));
  const missing = lines.filter((line) => !present.has(line));

  if (missing.length === 0) {
    return null;
  }

  const separator = source === "" || source.endsWith("\n") ? "" : "\n";

  return `${source}${separator}\n# Grimoire: generated by Warlock, rebuilt on demand\n${missing.join("\n")}\n`;
}

/**
 * Add a reporter call to the Vitest `reporters` list of a Vitest config text.
 *
 * - A `reporters: [...]` list gets the call at its end.
 * - A `test: { ... }` block without `reporters` gets `reporters: ["default", call]`.
 * - Nothing is changed when the call is already there.
 *
 * @param source The Vitest config text.
 * @param reporterCall The call to insert, e.g. `"grimoireReporter()"`.
 * @returns What happened, and the new text when there is any.
 */
export function insertVitestReporter(source: string, reporterCall: string): ConnectorInsertion {
  const name = reporterCall.slice(0, reporterCall.indexOf("("));

  if (new RegExp(`\\b${name}\\s*\\(`).test(source)) {
    return { status: "already-present" };
  }

  const reporters = /\breporters:\s*\[/.exec(source);

  if (reporters) {
    const open = reporters.index + reporters[0].length;
    const close = source.indexOf("]", open);

    if (close === -1) {
      return { status: "unrecognised" };
    }

    const inner = source.slice(open, close);
    const lastEntry = inner.replace(/[\s,]+$/, "");

    if (lastEntry.trim() === "") {
      return {
        status: "added",
        next: `${source.slice(0, open)}${reporterCall}${source.slice(close)}`,
      };
    }

    if (inner.includes("\n")) {
      const indent = /\n([ \t]*)[^\n]*$/.exec(lastEntry)?.[1] ?? "    ";
      const closeIndent = /\n([ \t]*)$/.exec(inner)?.[1] ?? "";

      return {
        status: "added",
        next: `${source.slice(0, open)}${lastEntry},\n${indent}${reporterCall},\n${closeIndent}${source.slice(close)}`,
      };
    }

    return {
      status: "added",
      next: `${source.slice(0, open)}${lastEntry}, ${reporterCall}${source.slice(close)}`,
    };
  }

  const testBlock = /\btest:\s*\{/.exec(source);

  if (!testBlock) {
    return { status: "unrecognised" };
  }

  const bodyStart = testBlock.index + testBlock[0].length;

  if (matchingBrace(source, bodyStart - 1) === -1) {
    return { status: "unrecognised" };
  }

  return {
    status: "added",
    next: addProperty(source, bodyStart, `reporters: ["default", ${reporterCall}]`),
  };
}

/**
 * Add a panel specifier to the `panels` list of an app's `src/config/devtools.ts`.
 *
 * @param source The config file's text.
 * @param panel The specifier, e.g. `"@warlock.js/grimoire/devtools"` (quotes added here).
 * @returns What happened, and the new text when there is any.
 */
export function insertDevtoolsPanel(source: string, panel: string): ConnectorInsertion {
  if (source.includes(panel)) {
    return { status: "already-present" };
  }

  const entry = JSON.stringify(panel);
  const panels = /\bpanels:\s*\[/.exec(source);

  if (panels) {
    return insertIntoArray(source, panels.index + panels[0].length, entry);
  }

  const object = /(?:export\s+default\s*|=\s*)\{/.exec(source);

  if (!object || matchingBrace(source, object.index + object[0].length - 1) === -1) {
    return { status: "unrecognised" };
  }

  return {
    status: "added",
    next: addProperty(source, object.index + object[0].length, `panels: [${entry}]`),
  };
}


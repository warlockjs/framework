import type * as ast from "../syntax/ast";
import type { SourceFinding } from "./source-ast";

/** An `index.ts(x)` inside an app module, at any depth. */
const APP_MODULE_INDEX = /^src\/app\/[^/]+\/(?:.+\/)?index\.[cm]?[jt]sx?$/;

/** A header comment that marks the barrel as written by a tool, not by hand. */
const GENERATED_HEADER = /^\s*(?:\/\/|\/\*)[^\n]*(?:auto-?generated|generated by|do not edit)/i;

/**
 * `WL9022`: an `index.ts` in an app module that only re-exports other files.
 *
 * Barrels are optional in Warlock. A hand-maintained one is a file every
 * feature has to edit, which is where merge conflicts and circular imports
 * come from, so this rule lets a team turn them into a finding. It is off by
 * default: `conventions-step` runs it only when `.warlock-check.json` sets
 * `rules.WL9022` to `"warning"` or `"error"`.
 */
export function barrelFindings(sourceFile: ast.SourceFile): SourceFinding[] {
  if (!APP_MODULE_INDEX.test(sourceFile.fileName)) return [];
  if (GENERATED_HEADER.test(sourceFile.text)) return [];

  const [first] = sourceFile.body;

  if (!first) return [];

  const onlyReExports = sourceFile.body.every(
    (statement) =>
      (statement.type === "ExportAllDeclaration" && statement.source !== null) ||
      (statement.type === "ExportNamedDeclaration" &&
        statement.declaration === null &&
        statement.source !== null),
  );

  if (!onlyReExports) return [];

  return [
    {
      code: "WL9022",
      severity: "warning",
      node: first,
      message:
        "This index.ts only re-exports other files. Import from the file that defines each export and delete the barrel.",
    },
  ];
}
